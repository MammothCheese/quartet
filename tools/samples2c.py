"""Turn drum samples (WAV) into a C table the firmware plays from flash: firmware/gen/lm1_samples.h

  python3 tools/samples2c.py DIR

DIR holds rossf's "Linn LM1 (LM-1) Drum Set" (Freesound pack 4919, Sampling+ 1.0, by rossf:
https://freesound.org/people/rossf/packs/4919/). The six used, in the kit's row order (KICK SNARE HAT OPEN; the CLAP and
PERC rows play the low and the high tom). Each is read (mono, 16 bit, 44.1 kHz), its near-silent tail trimmed (below
-60 dB of its peak, with a 5 ms fade), and stored 8-bit mu-law (companded, like the LM-1's own 8-bit samples), with
the 256-entry table that expands it back to 16 bit. Only the Python standard library is used."""
import sys
import wave
from pathlib import Path

SAMPLES = [   # (the file's name ends with, the row's name on the drum page)
    ("lm1-kick.wav", "KICK"),
    ("lm1-snare.wav", "SNARE"),
    ("lm1-hat-cl.wav", "HAT"),
    ("lm1-hat-open.wav", "OPEN"),
    ("lm1-tom-lo.wav", "TOM L"),
    ("lm1-tom-hi.wav", "TOM H"),
]
OUT = Path(__file__).resolve().parents[1] / "firmware" / "gen" / "lm1_samples.h"
BIAS, CLIP = 0x84, 32635


def mulaw_enc(s):
    sign = 0x80 if s < 0 else 0
    s = min(abs(s), CLIP) + BIAS
    exp = 7
    while exp > 0 and not (s & (0x4000 >> (7 - exp))):
        exp -= 1
    mant = (s >> (exp + 3)) & 0x0F
    return ~(sign | (exp << 4) | mant) & 0xFF


def mulaw_dec(u):
    u = ~u & 0xFF
    sign, exp, mant = u & 0x80, (u >> 4) & 7, u & 0x0F
    s = ((mant << 3) + BIAS) << exp
    s -= BIAS
    return -s if sign else s


def read(path):
    with wave.open(str(path)) as w:
        if w.getnchannels() != 1 or w.getsampwidth() != 2 or w.getframerate() != 44100:
            raise SystemExit(f"{path.name}: want mono 16-bit 44.1 kHz")
        raw = w.readframes(w.getnframes())
    return [int.from_bytes(raw[i:i + 2], "little", signed=True) for i in range(0, len(raw), 2)]


def trim(x):
    pk = max(abs(v) for v in x) or 1
    end = len(x)
    while end > 1 and abs(x[end - 1]) < pk / 1000:   # -60 dB
        end -= 1
    x = x[:end]
    fade = min(220, len(x))                           # 5 ms
    for i in range(fade):
        x[len(x) - fade + i] = x[len(x) - fade + i] * (fade - 1 - i) // fade
    return x


def main():
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    d = Path(sys.argv[1])
    out = ["/* SPDX-License-Identifier: CC-Sampling-Plus-1.0 (the sounds; see LICENSING.md) */",
           "/* generated by tools/samples2c.py from rossf's \"Linn LM1 (LM-1) Drum Set\" (Freesound pack 4919, Sampling+ 1.0,",
           " * https://freesound.org/people/rossf/packs/4919/): the LM-1 kit's samples, 8-bit mu-law at 44.1 kHz. Do not edit. */",
           "#pragma once", "#include <stdint.h>", "",
           "static const int16_t MULAW[256] = {"]
    dec = [mulaw_dec(u) for u in range(256)]
    for i in range(0, 256, 16):
        out.append("    " + ", ".join(str(v) for v in dec[i:i + 16]) + ",")
    out[-1] = out[-1].rstrip(",") + "};"
    total = 0
    names, lens = [], []
    for k, (suffix, label) in enumerate(SAMPLES):
        files = [p for p in d.iterdir() if p.name.lower().endswith(suffix)]
        if len(files) != 1:
            raise SystemExit(f"{suffix}: not found (or more than one) in {d}")
        x = trim(read(files[0]))
        enc = [mulaw_enc(v) for v in x]
        total += len(enc)
        names.append(label)
        lens.append(len(enc))
        out.append("")
        out.append(f"static const uint8_t LM1_S{k}[{len(enc)}] = {{   /* {label}: {files[0].name}, {len(enc) / 44.1:.0f} ms */")
        for i in range(0, len(enc), 24):
            out.append("    " + ", ".join(str(v) for v in enc[i:i + 24]) + ",")
        out[-1] = out[-1].rstrip(",") + "};"
    out += ["", "#define LM1_NSAMPLE 6u",
            "static const uint8_t *const LM1_DATA[LM1_NSAMPLE] = {" + ", ".join(f"LM1_S{k}" for k in range(6)) + "};",
            "static const uint32_t LM1_LEN[LM1_NSAMPLE] = {" + ", ".join(str(n) for n in lens) + "};",
            "static const char *const LM1_ROW[LM1_NSAMPLE] = {" + ", ".join(f'"{n}"' for n in names) + "};", ""]
    OUT.write_text("\n".join(out), encoding="utf-8")
    print(f"{OUT}: {total} bytes of samples ({total / 44100:.2f} s), " + ", ".join(f"{n} {l / 44.1:.0f} ms" for n, l in zip(names, lens)))


if __name__ == "__main__":
    main()
