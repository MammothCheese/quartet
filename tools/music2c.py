#!/usr/bin/env python3
"""Make firmware/gen/music_sym.h: the SCORE page's music symbols (clefs, rests, flat, natural) as 16-level bitmaps.

The glyphs are Noto's musical symbols (SIL Open Font License 1.1, see LICENSING.md), e.g. from Windows'
SansSerifCollection.ttf or NotoMusic-Regular.ttf. Each is drawn large, shrunk with box filtering to the height it
is used at (the staff's lines are 8 px apart) and kept as 4-bit alpha, two pixels a byte, rows rounded up to whole
bytes (as the fonts in felucca_font.h).

    python tools/music2c.py SansSerifCollection.ttf firmware/gen/music_sym.h

Needs Pillow (pip install pillow).
"""
import sys
from PIL import Image, ImageDraw, ImageFont

# name, code point, height in pixels
SYMS = [
    ('MS_TREBLE', 0x1D11E, 52),
    ('MS_BASS', 0x1D122, 24),
    ('MS_QREST', 0x1D13D, 21),
    ('MS_EREST', 0x1D13E, 14),
    ('MS_SREST', 0x1D13F, 19),
    ('MS_FLAT', 0x266D, 15),
    ('MS_NAT', 0x266E, 18),
]


def sym(f, cp, h):
    ch = chr(cp)
    bb = f.getbbox(ch)
    im = Image.new('L', (bb[2] - bb[0] + 8, bb[3] - bb[1] + 8), 0)
    ImageDraw.Draw(im).text((4 - bb[0], 4 - bb[1]), ch, fill=255, font=f)
    im = im.crop(im.getbbox())
    w = max(1, round(im.size[0] * h / im.size[1]))
    im = im.resize((w, h), Image.BOX)
    px = im.load()
    return w, [[(px[x, y] + 8) // 17 for x in range(w)] for y in range(h)]


def main():
    src, dst = sys.argv[1:3]
    f = ImageFont.truetype(src, 400)
    data, rows = [], []
    for name, cp, h in SYMS:
        w, a = sym(f, cp, h)
        rows.append((name, w, h, len(data)))
        for y in range(h):
            r = a[y] + [0] * (w & 1)
            data += [r[i] << 4 | r[i + 1] for i in range(0, len(r), 2)]
    out = ['/* generated by tools/music2c.py from Noto\'s musical symbols (SIL Open Font License 1.1, see LICENSING.md):',
           ' * clefs, rests, flat, natural for the SCORE page; 4-bit alpha, two pixels a byte */',
           '#pragma once', '#include <stdint.h>', '',
           'enum { ' + ', '.join(n for n, *_ in rows) + ', NMSYM };',
           'typedef struct { uint8_t w, h; uint16_t off; } msym_t;',
           'static const msym_t MSYM[NMSYM] = {' + ', '.join('{%d, %d, %d}' % (w, h, o) for _, w, h, o in rows) + '};',
           'static const uint8_t MSYM_DATA[%d] = {' % len(data)]
    for i in range(0, len(data), 24):
        out.append('    ' + ', '.join('0x%02x' % b for b in data[i:i + 24]) + ',')
    out.append('};')
    open(dst, 'w', encoding='utf-8', newline='\n').write('\n'.join(out) + '\n')
    print(len(data), 'bytes')


if __name__ == '__main__':
    main()
