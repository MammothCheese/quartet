#!/usr/bin/env python3
"""Make firmware/gen/felucca_font.h (FONT_S and FONT_L) from an outline font.

QUARTET's lettering is Liberation Sans Bold (SIL Open Font License 1.1), squeezed to a
narrow width. Each glyph is drawn 4x larger, squeezed, shrunk with box filtering and
kept as 16-level (4-bit) alpha: two pixels a byte, rows rounded up to whole bytes.

    python tools/ttf2font.py LiberationSans-Bold.ttf firmware/gen/felucca_font.h

Needs Pillow and NumPy (pip install pillow numpy).
"""
import sys
import numpy as np
from PIL import Image, ImageDraw, ImageFont

SS = 4          # supersampling
PAD = 2         # each bitmap starts this many pixels left of the pen
SQUEEZE = 0.82  # width of the narrow cut, against the regular one

# name, pixel size, cell height, baseline (from the top), letter spacing, boldening, first, last char
# (boldening: stems thickened by this many supersampled pixels across, as squeezing thins them)
CUTS = [
    ('FONT_S', 14, 16, 12, 1, 2, 32, 126),
    ('FONT_L', 31, 32, 27, 1, 3, 32, 95),      # capitals only: lower case folds to upper case (gfx.c glyph())
]


def cut(path, name, size, h, base, track, bold, first, last):
    f = ImageFont.truetype(path, size * SS)
    data, off, adv, bw = [], [], [], []
    for ch in map(chr, range(first, last + 1)):
        exact = f.getlength(ch) * SQUEEZE / SS
        a_px = round(exact)
        cw = int((f.getlength(ch) + size * SS) / SQUEEZE) + PAD * SS * 2
        im = Image.new('L', (cw, h * SS), 0)
        x0 = (PAD + (a_px - exact) / 2) * SS / SQUEEZE        # centred in its whole-pixel advance
        ImageDraw.Draw(im).text((x0, base * SS), ch, fill=255, font=f, anchor='ls')
        if bold:                                                # thicken sideways, evenly both ways
            m = np.array(im)
            im = Image.fromarray(np.max([np.roll(m, d, axis=1) for d in range(-(bold // 2), bold - bold // 2 + 1)], axis=0))
        w = max(1, round(cw * SQUEEZE / SS))
        im = im.resize((w, h), Image.BOX)
        px = im.load()
        a = [[(px[x, y] + 8) // 17 for x in range(w)] for y in range(h)]
        right = max([x + 1 for y in range(h) for x in range(w) if a[y][x]] or [1])
        off.append(len(data))
        bw.append(right)
        for y in range(h):
            row = a[y][:right] + [0] * (right & 1)
            data += [row[i] << 4 | row[i + 1] for i in range(0, len(row), 2)]
        adv.append(a_px + track)
    n = last - first + 1
    out = [f'static const uint8_t {name}_DATA[{len(data)}] = {{']
    for i in range(0, len(data), 24):
        out.append('    ' + ', '.join(f'0x{b:02x}' for b in data[i:i + 24]) + ',')
    out.append('};')
    out.append(f'static const uint16_t {name}_OFF[{n}] = {{{", ".join(map(str, off))}}};')
    out.append(f'static const uint8_t {name}_ADV[{n}] = {{{", ".join(map(str, adv))}}};')
    out.append(f'static const uint8_t {name}_BW[{n}] = {{{", ".join(map(str, bw))}}};')
    out.append(f'static const felucca_font_t {name} = {{ {h}, {PAD}, {first}, {last}, {name}_ADV, {name}_BW, {name}_OFF, {name}_DATA }};')
    return out, len(data)


def main():
    src, dst = sys.argv[1:3]
    lines = ['/* generated by tools/ttf2font.py from Liberation Sans Bold 2.1.5 (SIL Open Font License 1.1, see LICENSING.md),',
             f' * squeezed to {int(SQUEEZE * 100)} % width. FONT_S: ASCII 32..126, FONT_L: 32..95 (capitals). */',
             '#pragma once', '#include <stdint.h>', f'#define FONT_PAD {PAD}', '']
    for c in CUTS:
        body, size = cut(src, *c)
        lines += body + ['']
        print(c[0], size, 'bytes')
    open(dst, 'w', encoding='utf-8', newline='\n').write('\n'.join(lines))


if __name__ == '__main__':
    main()
